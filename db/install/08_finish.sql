                 'ERM_TRN_KPI_ACTUALS', 'ERM_TRN_KRI_READINGS', 'PER_MST_BUSINESS_PROCESS',
                 'PER_MST_BUSINESS_SUB_PROCESS', 'PER_MST_COMPUTATION_OUTPUT', 'PER_MST_CONTROL_CATEGORY',
                 'PER_MST_CONTROL_CLASIFICATION', 'PER_MST_CONTROL_CLASSIFICATION',
                 'PER_MST_CONTROL_DESIGN_EFFECTIVENESS', 'PER_MST_CONTROL_FREQUENCY', 'PER_MST_CONTROL_REGISTER',
