                 'PER_MST_RISK_STATEMENT', 'PER_MST_RISK_SUB_CATEGORY', 'PER_MST_RISK_TYPE', 'PER_MST_ROLES',
                 'PER_MST_USER_DETAILS', 'PER_MST_USER_ROLES_MAPPING', 'PER_TRN_CONTROL_IMPLEMENTATION',
