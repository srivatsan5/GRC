-- =============================================================================
-- V3  Tables for the modules that used to live only in the browser
--
--   ERM_MST_CONTROL            control library
--   ERM_LNK_CONTROL_RISK       control  ↔ risk register links
--   ERM_MST_POLICY             policy register
--   ERM_LNK_POLICY_CONTROL     policy   ↔ control links
--   ERM_TRN_INCIDENT           incidents / loss events
--   ERM_LNK_INCIDENT_RISK      incident ↔ risk register links
--   ERM_MST_VENDOR             third-party (vendor) register
--   ERM_MST_BCP_PLAN           business continuity plans
--   ERM_MST_SCENARIO           stress / scenario analysis
--   ERM_MST_RISK_APPETITE      risk appetite statements
--   ERM_TRN_APPROVAL_REQUEST   maker-checker approval requests
--   ERM_TRN_APPROVAL_STEP      ordered approval steps of a request
--   ERM_MST_APP_SETTING        organisation settings (key → JSON)
--
-- KRIs reuse ERM_MST_KRI_DEFINITION / ERM_TRN_KRI_READINGS (extended in V2);
-- assessment cycles reuse ERM_TRN_ASSESSMENT_CYCLE.
--
-- Every table has a UUID identity key and CREATED_/UPDATED_ BY/ON columns that the
-- API fills in. All are REST-enabled with authentication required. Safe to re-run.
-- =============================================================================

BEGIN
  pericope_ddl.create_table('ERM_MST_CONTROL', q'[
    UUID                    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMC PRIMARY KEY,
    CONTROL_CODE            VARCHAR2(50)   NOT NULL CONSTRAINT UQ_EMC_CODE UNIQUE,
    CONTROL_NAME            VARCHAR2(200)  NOT NULL,
    DESCRIPTION             VARCHAR2(4000),
    CONTROL_TYPE            VARCHAR2(20)   CONSTRAINT CHK_EMC_TYPE CHECK (CONTROL_TYPE IN ('Preventive', 'Detective', 'Corrective', 'Compensating')),
    CONTROL_NATURE          VARCHAR2(20)   CONSTRAINT CHK_EMC_NATURE CHECK (CONTROL_NATURE IN ('Manual', 'Automated', 'Hybrid')),
    FREQUENCY               VARCHAR2(20)   CONSTRAINT CHK_EMC_FREQ CHECK (FREQUENCY IN ('Continuous', 'Daily', 'Weekly', 'Monthly', 'Quarterly', 'Annual', 'Event-driven')),
    OWNER_NAME              VARCHAR2(200),
    FRAMEWORKS              VARCHAR2(1000),
    DESIGN_EFFECTIVENESS    NUMBER(1)      CONSTRAINT CHK_EMC_DE CHECK (DESIGN_EFFECTIVENESS BETWEEN 1 AND 5),
    OPERATING_EFFECTIVENESS NUMBER(1)      CONSTRAINT CHK_EMC_OE CHECK (OPERATING_EFFECTIVENESS BETWEEN 1 AND 5),
    LAST_TESTED_ON          DATE,
    STATUS                  VARCHAR2(20)   DEFAULT 'Active' NOT NULL CONSTRAINT CHK_EMC_STATUS CHECK (STATUS IN ('Draft', 'Active', 'Retired')),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_LNK_CONTROL_RISK', q'[
    UUID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ELCR PRIMARY KEY,
    CONTROL_UUID NUMBER NOT NULL CONSTRAINT FK_ELCR_CONTROL REFERENCES ERM_MST_CONTROL (UUID) ON DELETE CASCADE,
    RISK_UUID    NUMBER NOT NULL,
    CONSTRAINT UQ_ELCR UNIQUE (CONTROL_UUID, RISK_UUID),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP]');

  pericope_ddl.create_table('ERM_MST_POLICY', q'[
    UUID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMP PRIMARY KEY,
    POLICY_CODE       VARCHAR2(50)  NOT NULL CONSTRAINT UQ_EMP_CODE UNIQUE,
    TITLE             VARCHAR2(300) NOT NULL,
    CATEGORY          VARCHAR2(100),
    VERSION_LABEL     VARCHAR2(20),
    OWNER_NAME        VARCHAR2(200),
    EFFECTIVE_DATE    DATE,
    NEXT_REVIEW_DATE  DATE,
    ACKNOWLEDGED_PCT  NUMBER(5,2)   CONSTRAINT CHK_EMP_ACK CHECK (ACKNOWLEDGED_PCT BETWEEN 0 AND 100),
    STATUS            VARCHAR2(20)  DEFAULT 'Draft' NOT NULL CONSTRAINT CHK_EMP_STATUS CHECK (STATUS IN ('Draft', 'Active', 'Retired')),
    CONSTRAINT CHK_EMP_DATES CHECK (NEXT_REVIEW_DATE IS NULL OR EFFECTIVE_DATE IS NULL OR NEXT_REVIEW_DATE >= EFFECTIVE_DATE),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_LNK_POLICY_CONTROL', q'[
    UUID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ELPC PRIMARY KEY,
    POLICY_UUID  NUMBER NOT NULL CONSTRAINT FK_ELPC_POLICY  REFERENCES ERM_MST_POLICY (UUID) ON DELETE CASCADE,
    CONTROL_UUID NUMBER NOT NULL CONSTRAINT FK_ELPC_CONTROL REFERENCES ERM_MST_CONTROL (UUID) ON DELETE CASCADE,
    CONSTRAINT UQ_ELPC UNIQUE (POLICY_UUID, CONTROL_UUID),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP]');

  pericope_ddl.create_table('ERM_TRN_INCIDENT', q'[
    UUID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ETI PRIMARY KEY,
    INCIDENT_REF      VARCHAR2(50)   CONSTRAINT UQ_ETI_REF UNIQUE,
    TITLE             VARCHAR2(300)  NOT NULL,
    DESCRIPTION       VARCHAR2(4000),
    SEVERITY          VARCHAR2(10)   NOT NULL CONSTRAINT CHK_ETI_SEV CHECK (SEVERITY IN ('Low', 'Medium', 'High', 'Critical')),
    STATUS            VARCHAR2(20)   DEFAULT 'Open' NOT NULL CONSTRAINT CHK_ETI_STATUS CHECK (STATUS IN ('Open', 'Investigating', 'Mitigated', 'Closed')),
    CATEGORY          VARCHAR2(100),
    REPORTED_BY       VARCHAR2(200),
    ASSIGNED_TO       VARCHAR2(200),
    OCCURRED_ON       DATE,
    REPORTED_ON       DATE           DEFAULT TRUNC(SYSDATE) NOT NULL,
    CLOSED_ON         DATE,
    ROOT_CAUSE        VARCHAR2(4000),
    CORRECTIVE_ACTION VARCHAR2(4000),
    LOSS_AMOUNT       NUMBER(18,2)   CONSTRAINT CHK_ETI_LOSS CHECK (LOSS_AMOUNT >= 0),
    CONSTRAINT CHK_ETI_CLOSED CHECK (CLOSED_ON IS NULL OR CLOSED_ON >= REPORTED_ON),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_LNK_INCIDENT_RISK', q'[
    UUID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ELIR PRIMARY KEY,
    INCIDENT_UUID NUMBER NOT NULL CONSTRAINT FK_ELIR_INCIDENT REFERENCES ERM_TRN_INCIDENT (UUID) ON DELETE CASCADE,
    RISK_UUID     NUMBER NOT NULL,
    CONSTRAINT UQ_ELIR UNIQUE (INCIDENT_UUID, RISK_UUID),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP]');

  pericope_ddl.create_table('ERM_MST_VENDOR', q'[
    UUID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMV PRIMARY KEY,
    VENDOR_NAME        VARCHAR2(200) NOT NULL CONSTRAINT UQ_EMV_NAME UNIQUE,
    CATEGORY           VARCHAR2(100),
    TIER               VARCHAR2(10)  NOT NULL CONSTRAINT CHK_EMV_TIER CHECK (TIER IN ('Critical', 'High', 'Medium', 'Low')),
    COUNTRY_CODE       VARCHAR2(2),
    CONTRACT_VALUE     NUMBER(18,2)  CONSTRAINT CHK_EMV_VALUE CHECK (CONTRACT_VALUE >= 0),
    RISK_SCORE         NUMBER(3)     CONSTRAINT CHK_EMV_SCORE CHECK (RISK_SCORE BETWEEN 1 AND 100),
    LAST_ASSESSMENT_ON DATE,
    NEXT_REVIEW_ON     DATE,
    CONTACT_EMAIL      VARCHAR2(254),
    OPEN_FINDINGS      NUMBER(5)     DEFAULT 0 CONSTRAINT CHK_EMV_FINDINGS CHECK (OPEN_FINDINGS >= 0),
    STATUS             VARCHAR2(20)  DEFAULT 'Active' NOT NULL CONSTRAINT CHK_EMV_STATUS CHECK (STATUS IN ('Onboarding', 'Active', 'Offboarding', 'Exited')),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_MST_BCP_PLAN', q'[
    UUID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMB PRIMARY KEY,
    PLAN_NAME      VARCHAR2(200) NOT NULL,
    SCOPE          VARCHAR2(1000),
    RTO_HOURS      NUMBER(6,1)   NOT NULL CONSTRAINT CHK_EMB_RTO CHECK (RTO_HOURS > 0),
    RPO_HOURS      NUMBER(6,1)   NOT NULL CONSTRAINT CHK_EMB_RPO CHECK (RPO_HOURS >= 0),
    OWNER_NAME     VARCHAR2(200),
    LAST_TESTED_ON DATE,
    NEXT_TEST_ON   DATE,
    STATUS         VARCHAR2(20)  DEFAULT 'Draft' NOT NULL CONSTRAINT CHK_EMB_STATUS CHECK (STATUS IN ('Draft', 'Active', 'Retired')),
    CONSTRAINT CHK_EMB_RPO_RTO CHECK (RPO_HOURS <= RTO_HOURS),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_MST_SCENARIO', q'[
    UUID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMS PRIMARY KEY,
    SCENARIO_NAME   VARCHAR2(200) NOT NULL,
    DESCRIPTION     VARCHAR2(4000),
    SCENARIO_TYPE   VARCHAR2(20)  CONSTRAINT CHK_EMS_TYPE CHECK (SCENARIO_TYPE IN ('Stress Test', 'What-if', 'Reverse Stress', 'Tail Risk')),
    CATEGORY        VARCHAR2(100),
    SHOCK_PCT       NUMBER(7,2),
    BASELINE_LOSS   NUMBER(18,2)  CONSTRAINT CHK_EMS_BASE CHECK (BASELINE_LOSS >= 0),
    STRESSED_LOSS   NUMBER(18,2)  CONSTRAINT CHK_EMS_STRESS CHECK (STRESSED_LOSS >= 0),
    PROBABILITY_PCT NUMBER(5,2)   CONSTRAINT CHK_EMS_PROB CHECK (PROBABILITY_PCT BETWEEN 0 AND 100),
    OWNER_NAME      VARCHAR2(200),
    LAST_RUN_ON     TIMESTAMP,
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_MST_RISK_APPETITE', q'[
    UUID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMRA PRIMARY KEY,
    CATEGORY         VARCHAR2(100) NOT NULL CONSTRAINT UQ_EMRA_CATEGORY UNIQUE,
    STATEMENT        VARCHAR2(4000) NOT NULL,
    POSTURE          VARCHAR2(20)  NOT NULL CONSTRAINT CHK_EMRA_POSTURE CHECK (POSTURE IN ('Averse', 'Cautious', 'Open', 'Hungry')),
    TOLERANCE_SCORE  NUMBER(2)     NOT NULL CONSTRAINT CHK_EMRA_TOL CHECK (TOLERANCE_SCORE BETWEEN 1 AND 25),
    APPROVED_BY      VARCHAR2(200),
    APPROVED_ON      DATE,
    REVIEW_FREQUENCY VARCHAR2(20)  CONSTRAINT CHK_EMRA_REVIEW CHECK (REVIEW_FREQUENCY IN ('Quarterly', 'Semi-annual', 'Annual')),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_TRN_APPROVAL_REQUEST', q'[
    UUID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ETAR PRIMARY KEY,
    TITLE          VARCHAR2(300) NOT NULL,
    REQUEST_TYPE   VARCHAR2(30)  NOT NULL CONSTRAINT CHK_ETAR_TYPE CHECK (REQUEST_TYPE IN ('Risk Assessment', 'Mitigation Plan', 'Control Change', 'Policy Update', 'Risk Acceptance')),
    BUSINESS_UNIT  VARCHAR2(100),
    AMOUNT         NUMBER(18,2)  CONSTRAINT CHK_ETAR_AMOUNT CHECK (AMOUNT >= 0),
    DETAILS        VARCHAR2(4000),
    STATUS         VARCHAR2(20)  DEFAULT 'Pending' NOT NULL CONSTRAINT CHK_ETAR_STATUS CHECK (STATUS IN ('Pending', 'In Review', 'Approved', 'Rejected', 'Withdrawn')),
    SUBMITTED_BY   VARCHAR2(254) NOT NULL,
    SUBMITTED_NAME VARCHAR2(200),
    SUBMITTED_ON   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CLOSED_ON      TIMESTAMP,
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_TRN_APPROVAL_STEP', q'[
    UUID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ETAS PRIMARY KEY,
    REQUEST_UUID  NUMBER       NOT NULL CONSTRAINT FK_ETAS_REQUEST REFERENCES ERM_TRN_APPROVAL_REQUEST (UUID) ON DELETE CASCADE,
    STEP_NO       NUMBER(2)    NOT NULL,
    APPROVER_ROLE VARCHAR2(30) NOT NULL CONSTRAINT CHK_ETAS_ROLE CHECK (APPROVER_ROLE IN ('Risk Manager', 'Administrator')),
    DECISION      VARCHAR2(10) CONSTRAINT CHK_ETAS_DECISION CHECK (DECISION IN ('Approved', 'Rejected')),
    DECIDED_BY    VARCHAR2(254),
    DECIDED_NAME  VARCHAR2(200),
    DECIDED_ON    TIMESTAMP,
    COMMENTS      VARCHAR2(2000),
    CONSTRAINT UQ_ETAS_STEP UNIQUE (REQUEST_UUID, STEP_NO),
    CONSTRAINT CHK_ETAS_REJECT_COMMENT CHECK (DECISION IS NULL OR DECISION = 'Approved' OR COMMENTS IS NOT NULL),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  pericope_ddl.create_table('ERM_MST_APP_SETTING', q'[
    UUID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_EMAS PRIMARY KEY,
    SETTING_KEY   VARCHAR2(100) NOT NULL CONSTRAINT UQ_EMAS_KEY UNIQUE,
    SETTING_VALUE VARCHAR2(4000) CONSTRAINT CHK_EMAS_JSON CHECK (SETTING_VALUE IS JSON),
    CREATED_BY VARCHAR2(254), CREATED_ON TIMESTAMP DEFAULT SYSTIMESTAMP, UPDATED_BY VARCHAR2(254), UPDATED_ON TIMESTAMP]');

  -- Join / filter indexes
  pericope_ddl.create_index('IX_ELCR_RISK',      'ERM_LNK_CONTROL_RISK',     'RISK_UUID');
  pericope_ddl.create_index('IX_ELPC_CONTROL',   'ERM_LNK_POLICY_CONTROL',   'CONTROL_UUID');
  pericope_ddl.create_index('IX_ELIR_RISK',      'ERM_LNK_INCIDENT_RISK',    'RISK_UUID');
  pericope_ddl.create_index('IX_ETI_STATUS',     'ERM_TRN_INCIDENT',         'STATUS, SEVERITY');
  pericope_ddl.create_index('IX_ETAR_STATUS',    'ERM_TRN_APPROVAL_REQUEST', 'STATUS');
  pericope_ddl.create_index('IX_ETAR_SUBMITTER', 'ERM_TRN_APPROVAL_REQUEST', 'SUBMITTED_BY');

  -- Links to the risk register (removed together with the risk)
  pericope_ddl.add_fk('ERM_LNK_CONTROL_RISK',  'FK_ELCR_RISK', 'RISK_UUID', 'PER_TRN_IDENTIFY_RISK', 'UUID', 'CASCADE');
  pericope_ddl.add_fk('ERM_LNK_INCIDENT_RISK', 'FK_ELIR_RISK', 'RISK_UUID', 'PER_TRN_IDENTIFY_RISK', 'UUID', 'CASCADE');

  -- REST endpoints (authentication required)
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
              'ERM_MST_CONTROL', 'ERM_LNK_CONTROL_RISK', 'ERM_MST_POLICY', 'ERM_LNK_POLICY_CONTROL',
              'ERM_TRN_INCIDENT', 'ERM_LNK_INCIDENT_RISK', 'ERM_MST_VENDOR', 'ERM_MST_BCP_PLAN',
              'ERM_MST_SCENARIO', 'ERM_MST_RISK_APPETITE', 'ERM_TRN_APPROVAL_REQUEST',
              'ERM_TRN_APPROVAL_STEP', 'ERM_MST_APP_SETTING'))) LOOP
    pericope_ddl.enable_rest(t.name);
  END LOOP;
END;
