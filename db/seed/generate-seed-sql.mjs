// Writes demo_data.sql from demo-rows.mjs.   node db/seed/generate-seed-sql.mjs
import { writeFileSync } from 'node:fs'
import { demoRows } from './demo-rows.mjs'

const DATE_COLUMNS = /(_ON|_DATE)$/
const lit = (col, v) => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'object' && v.$ref) {
    const [table, keyCol, keyVal] = v.$ref
    return `(SELECT UUID FROM ${table} WHERE ${keyCol} = ${lit(keyCol, keyVal)})`
  }
  if (typeof v === 'number') return String(v)
  const s = String(v).replace(/'/g, "''")
  // DATE literals also convert implicitly into TIMESTAMP columns.
  if (DATE_COLUMNS.test(col) && /^\d{4}-\d{2}-\d{2}$/.test(s)) return `DATE '${s}'`
  return `'${s}'`
}

const rows = demoRows()
let sql = `-- Optional DEMO data for the Pericope modules (controls, policies, incidents, vendors,
-- BCP, scenarios, risk appetite, KRIs, approval workflow). Generated by generate-seed-sql.mjs.
-- Run once, after migrations V1–V4, only on a demo/test schema. Remove with:
--   DELETE FROM <table> WHERE CREATED_BY = 'demo-seed';   (KRI readings: RECORDED_BY = 'demo-seed')
SET DEFINE OFF
`
for (const [table, list] of Object.entries(rows)) {
  if (!list.length) continue
  sql += `\n-- ${table} (${list.length})\n`
  for (const r of list) {
    const cols = Object.keys(r)
    sql += `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map(c => lit(c, r[c])).join(', ')});\n`
  }
}
sql += '\nCOMMIT;\n'
writeFileSync(new URL('./demo_data.sql', import.meta.url), sql)
console.log('wrote db/seed/demo_data.sql')
