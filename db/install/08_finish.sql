                 'PER_TRN_MITIGATION_PLANS', 'PER_TRN_MITIGATION_TYPE', 'PER_TRN_RISK_MONITORING')) LOOP
    grant_role('oracle.dbtools.role.autorest.' || v_schema || '.' || o.object_name);
