#!/usr/bin/env node
/**
 * Rebuilds every generated install file, then the one-file bundle:
 *   02_tables.sql, 03_foreign_keys.sql, 08_finish.sql   (build.mjs, from source/pericope_erm_ddl.tsv)
 *   07_mock_data.sql                                    (mock.mjs)
 *   install_all.sql                                     (01 → 08 in order, for Database Actions)
 *
 *   node db/install/tools/build-all.mjs      (or: npm run db:install)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildSchema } from './build.mjs'
import { buildMock } from './mock.mjs'

const install = join(dirname(fileURLToPath(import.meta.url)), '..')
const db = join(install, '..')

buildSchema()
buildMock()

const steps = [
  ['01', 'Erase the schema', join(install, '01_drop_all.sql')],
  ['02', 'Tables', join(install, '02_tables.sql')],
  ['03', 'Foreign keys', join(install, '03_foreign_keys.sql')],
  ['04', 'App alignment', join(install, '04_app_alignment.sql')],
  ['05a', 'Migration V1', join(db, 'migrations', 'V1__pericope_ddl_helpers.sql')],
  ['05b', 'Migration V2', join(db, 'migrations', 'V2__risk_scoring_and_integrity.sql')],
  ['05c', 'Migration V3', join(db, 'migrations', 'V3__erm_module_tables.sql')],
  ['05d', 'Migration V4', join(db, 'migrations', 'V4__correctly_spelled_views.sql')],
  ['05e', 'Migration V5', join(db, 'migrations', 'V5__app_alignment.sql')],
  ['06', 'Module demo data', join(db, 'seed', 'demo_data.sql')],
  ['07', 'Demo data for every table', join(install, '07_mock_data.sql')],
  ['08', 'Finish: keys, REST, OAuth client', join(install, '08_finish.sql')],
]

let out = `-- =============================================================================
-- Pericope: complete install in one script (steps 01 → 08 of db/install/README.md)
--
-- ERASES EVERYTHING in the schema you are signed in as, then creates the tables, keys,
-- migrations and demo data, REST-enables what the API uses and creates its OAuth client.
-- Sign in to Database Actions as PERICOPE_ERM (never ADMIN), open SQL, paste or open this
-- file and press "Run Script" (F5). It takes a few minutes.
--
-- Generated by db/install/tools/build-all.mjs. Do not edit by hand.
-- =============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
`
for (const [no, title, file] of steps) {
  out += `\n-- ############################################################################\n-- STEP ${no}: ${title}\n-- ############################################################################\n`
  out += `PROMPT ===== Step ${no}: ${title}\n`
  out += readFileSync(file, 'utf8').replace(/\s+$/, '') + '\n'
}
writeFileSync(join(install, 'install_all.sql'), out)
console.log(`install_all.sql: ${steps.length} steps, ${(out.length / 1024).toFixed(0)} KB`)
