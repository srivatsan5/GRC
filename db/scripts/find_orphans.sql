-- Rows that point at a parent that does not exist. The V2/V3 foreign keys are
-- ENABLE NOVALIDATE, so these old rows were tolerated; fix or delete them, then
-- optionally run:  ALTER TABLE <table> MODIFY CONSTRAINT <fk> VALIDATE;
-- Read-only: nothing here changes data.

SELECT 'PER_TRN_CONTROL_IMPLEMENTATION' AS child_table, c.UUID AS child_uuid, c.IDENTIFY_RISK_UUID AS missing_parent
  FROM PER_TRN_CONTROL_IMPLEMENTATION c
 WHERE c.IDENTIFY_RISK_UUID IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM PER_TRN_IDENTIFY_RISK r WHERE r.UUID = c.IDENTIFY_RISK_UUID)
UNION ALL
SELECT 'PER_TRN_RISK_MONITORING', m.UUID, m.IDENTIFY_RISK_UUID
  FROM PER_TRN_RISK_MONITORING m
 WHERE m.IDENTIFY_RISK_UUID IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM PER_TRN_IDENTIFY_RISK r WHERE r.UUID = m.IDENTIFY_RISK_UUID)
UNION ALL
SELECT 'PER_TRN_IDENTIFY_RISK (cycle)', r.UUID, r.ASSESSMENT_CYCLE_UUID
  FROM PER_TRN_IDENTIFY_RISK r
 WHERE r.ASSESSMENT_CYCLE_UUID IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM ERM_TRN_ASSESSMENT_CYCLE c WHERE c.UUID = r.ASSESSMENT_CYCLE_UUID)
UNION ALL
SELECT 'ERM_TRN_KRI_READINGS', k.UUID, k.KRI_UUID
  FROM ERM_TRN_KRI_READINGS k
 WHERE NOT EXISTS (SELECT 1 FROM ERM_MST_KRI_DEFINITION d WHERE d.UUID = k.KRI_UUID);
