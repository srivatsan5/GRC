-- =============================================================================
-- V1  Pericope DDL helpers
-- Small idempotent helpers used by later migrations, so each migration can be
-- re-run safely on a schema that already has some of its objects.
-- Oracle Autonomous Database 19c+ (ORDS installed). Run as the schema owner.
--
-- Every message (and especially every WARNING) is also written to the table
-- PERICOPE_MIGRATION_LOG, because tools such as Flyway don't show DBMS_OUTPUT:
--   SELECT * FROM pericope_migration_log WHERE log_level = 'WARNING' ORDER BY logged_on;
-- =============================================================================

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'PERICOPE_MIGRATION_LOG';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PERICOPE_MIGRATION_LOG (
      LOG_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      LOGGED_ON TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      LOG_LEVEL VARCHAR2(10) NOT NULL,
      MESSAGE   VARCHAR2(4000))';
  END IF;
END;
/

CREATE OR REPLACE PACKAGE pericope_ddl AUTHID CURRENT_USER AS
  -- Create a table from its column list, e.g. create_table('T', 'ID NUMBER PRIMARY KEY, NAME VARCHAR2(10)')
  PROCEDURE create_table(p_table VARCHAR2, p_columns CLOB);
  PROCEDURE add_column(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2);
  PROCEDURE create_index(p_index VARCHAR2, p_table VARCHAR2, p_columns VARCHAR2);
  -- p_definition is everything after "ADD CONSTRAINT <name>", e.g. 'CHECK (x > 0)'
  PROCEDURE add_constraint(p_table VARCHAR2, p_constraint VARCHAR2, p_definition VARCHAR2);
  -- Foreign key, fully validated. If existing rows point at missing parents the key is NOT added
  -- (a WARNING says how many rows; fix them with db/scripts/find_orphans.sql and re-run).
  -- p_on_delete: NULL (restrict), 'CASCADE' or 'SET NULL'.
  PROCEDURE add_fk(p_table VARCHAR2, p_constraint VARCHAR2, p_column VARCHAR2,
                   p_ref_table VARCHAR2, p_ref_column VARCHAR2 DEFAULT 'UUID', p_on_delete VARCHAR2 DEFAULT NULL);
  PROCEDURE log_msg(p_level VARCHAR2, p_message VARCHAR2);
  -- Expose a table/view through ORDS AutoREST with authentication required.
  PROCEDURE enable_rest(p_object VARCHAR2, p_type VARCHAR2 DEFAULT 'TABLE');
  FUNCTION table_exists(p_table VARCHAR2) RETURN BOOLEAN;
END pericope_ddl;
/

CREATE OR REPLACE PACKAGE BODY pericope_ddl AS
  PROCEDURE log_msg(p_level VARCHAR2, p_message VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    DBMS_OUTPUT.PUT_LINE(p_level || ': ' || p_message);
    EXECUTE IMMEDIATE 'INSERT INTO PERICOPE_MIGRATION_LOG (LOG_LEVEL, MESSAGE) VALUES (:1, :2)'
      USING p_level, SUBSTR(p_message, 1, 4000);
    COMMIT;
  END;

  FUNCTION table_exists(p_table VARCHAR2) RETURN BOOLEAN IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM user_objects
     WHERE object_name = UPPER(p_table) AND object_type IN ('TABLE', 'VIEW');
    RETURN n > 0;
  END;

  PROCEDURE create_table(p_table VARCHAR2, p_columns CLOB) IS
  BEGIN
    IF table_exists(p_table) THEN
      log_msg('INFO', 'table ' || p_table || ' already exists');
      RETURN;
    END IF;
    EXECUTE IMMEDIATE 'CREATE TABLE ' || p_table || ' (' || p_columns || ')';
    log_msg('INFO', 'created table ' || p_table);
  END;

  PROCEDURE add_column(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
    n NUMBER;
  BEGIN
    IF NOT table_exists(p_table) THEN
      log_msg('INFO', 'skip column ' || p_table || '.' || p_column || ': table missing');
      RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM user_tab_columns
     WHERE table_name = UPPER(p_table) AND column_name = UPPER(p_column);
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_column || ' ' || p_definition || ')';
      log_msg('INFO', 'added column ' || p_table || '.' || p_column);
    END IF;
  END;

  PROCEDURE create_index(p_index VARCHAR2, p_table VARCHAR2, p_columns VARCHAR2) IS
    n NUMBER;
    already_indexed EXCEPTION;
    PRAGMA EXCEPTION_INIT(already_indexed, -1408);
    no_column EXCEPTION;
    PRAGMA EXCEPTION_INIT(no_column, -904);
  BEGIN
    IF NOT table_exists(p_table) THEN
      log_msg('INFO', 'skip index ' || p_index || ': table missing');
      RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM user_indexes WHERE index_name = UPPER(p_index);
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'CREATE INDEX ' || p_index || ' ON ' || p_table || ' (' || p_columns || ')';
      log_msg('INFO', 'created index ' || p_index);
    END IF;
  EXCEPTION
    WHEN already_indexed THEN log_msg('INFO', 'skip index ' || p_index || ': columns already indexed');
    WHEN no_column THEN log_msg('INFO', 'skip index ' || p_index || ': column missing');
  END;

  PROCEDURE add_constraint(p_table VARCHAR2, p_constraint VARCHAR2, p_definition VARCHAR2) IS
    n NUMBER;
  BEGIN
    IF NOT table_exists(p_table) THEN
      log_msg('INFO', 'skip constraint ' || p_constraint || ': table missing');
      RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM user_constraints WHERE constraint_name = UPPER(p_constraint);
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD CONSTRAINT ' || p_constraint || ' ' || p_definition;
      log_msg('INFO', 'added constraint ' || p_constraint);
    END IF;
  EXCEPTION
    -- A constraint that can't be added (e.g. the referenced key is not unique) must not stop the
    -- migration; it is reported so it can be fixed by hand.
    WHEN OTHERS THEN
      log_msg('WARNING', 'could not add ' || p_constraint || ' on ' || p_table || ': ' || SQLERRM);
  END;

  PROCEDURE add_fk(p_table VARCHAR2, p_constraint VARCHAR2, p_column VARCHAR2,
                   p_ref_table VARCHAR2, p_ref_column VARCHAR2 DEFAULT 'UUID', p_on_delete VARCHAR2 DEFAULT NULL) IS
    n       NUMBER;
    orphans NUMBER;
  BEGIN
    IF NOT table_exists(p_table) OR NOT table_exists(p_ref_table) THEN
      log_msg('INFO', 'skip ' || p_constraint || ': table missing');
      RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM user_constraints WHERE constraint_name = UPPER(p_constraint);
    IF n > 0 THEN
      RETURN;
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ' || p_table || ' c WHERE c.' || p_column || ' IS NOT NULL'
      || ' AND NOT EXISTS (SELECT 1 FROM ' || p_ref_table || ' p WHERE p.' || p_ref_column || ' = c.' || p_column || ')'
      INTO orphans;
    IF orphans > 0 THEN
      log_msg('WARNING', 'foreign key ' || p_constraint || ' not added: ' || orphans || ' row(s) of ' || p_table
        || ' reference a missing ' || p_ref_table || '. Fix them (db/scripts/find_orphans.sql) and re-run this migration.');
      RETURN;
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD CONSTRAINT ' || p_constraint
      || ' FOREIGN KEY (' || p_column || ') REFERENCES ' || p_ref_table || ' (' || p_ref_column || ')'
      || CASE WHEN p_on_delete IS NOT NULL THEN ' ON DELETE ' || p_on_delete END;
    log_msg('INFO', 'added foreign key ' || p_constraint);
  EXCEPTION
    WHEN OTHERS THEN
      log_msg('WARNING', 'could not add ' || p_constraint || ' on ' || p_table || ': ' || SQLERRM);
  END;

  PROCEDURE enable_rest(p_object VARCHAR2, p_type VARCHAR2 DEFAULT 'TABLE') IS
  BEGIN
    EXECUTE IMMEDIATE q'[
      BEGIN
        ORDS.ENABLE_OBJECT(
          p_enabled        => TRUE,
          p_schema         => SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA'),
          p_object         => :obj,
          p_object_type    => :typ,
          p_object_alias   => LOWER(:obj),
          p_auto_rest_auth => TRUE);
      END;]' USING UPPER(p_object), UPPER(p_type);  -- in a PL/SQL block a repeated placeholder binds once
    log_msg('INFO', 'REST-enabled (auth required) ' || p_object);
  EXCEPTION
    WHEN OTHERS THEN
      log_msg('WARNING', 'could not REST-enable ' || p_object || ': ' || SQLERRM);
  END;
END pericope_ddl;
/
