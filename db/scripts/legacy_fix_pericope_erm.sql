--------------------------------------------------------------------------------
-- PERICOPE ERM - DATABASE REMEDIATION & HARDENING SCRIPT  (APEX-safe edition)
--------------------------------------------------------------------------------
-- PURPOSE
--   Fixes the ORA-04098 invalid-trigger error that blocks every INSERT/UPDATE
--   on the RCSA tables, recompiles invalid objects, cleans corrupt data
--   (DQ-01..DQ-08), and adds guard rails so the same class of error cannot recur.
--
-- HOW TO RUN
--   Oracle APEX  ->  SQL Workshop  ->  SQL Scripts  ->  Upload/Create  -> Run
--   Run as the schema owner of the PER_* tables (e.g. PERICOPE_ERM).
--
-- WHY THIS VERSION
--   Every unit is a PL/SQL block terminated by "/".  There are NO SQL*Plus
--   commands (SET / PROMPT) and NO bare multi-line SELECTs, because the APEX
--   SQL Scripts parser rejects those.  All diagnostics print via DBMS_OUTPUT
--   (shown in the script results panel).
--
-- SAFETY
--   * Idempotent  - safe to run repeatedly.
--   * Defensive   - each risky step is wrapped; one failure never aborts the rest.
--   * Non-destructive to good data - cleanup only touches provably-corrupt rows.
--------------------------------------------------------------------------------


--==============================================================================
-- STEP 0  -  DIAGNOSTICS (printed to DBMS_OUTPUT)
--==============================================================================
DECLARE
  v_any BOOLEAN := FALSE;
BEGIN
  DBMS_OUTPUT.PUT_LINE('==== INVALID OBJECTS ====');
  FOR r IN (SELECT object_name, object_type
            FROM   user_objects
            WHERE  status = 'INVALID'
            ORDER  BY object_type, object_name) LOOP
    v_any := TRUE;
    DBMS_OUTPUT.PUT_LINE('  ' || RPAD(r.object_type, 16) || ' ' || r.object_name);
  END LOOP;
  IF NOT v_any THEN DBMS_OUTPUT.PUT_LINE('  (none)'); END IF;

  DBMS_OUTPUT.PUT_LINE('==== COMPILE ERRORS ====');
  v_any := FALSE;
  FOR r IN (SELECT name, type, line, text
            FROM   user_errors
            ORDER  BY name, sequence) LOOP
    v_any := TRUE;
    DBMS_OUTPUT.PUT_LINE('  ' || r.name || ' (' || r.type || ') line ' || r.line || ': ' || SUBSTR(r.text,1,120));
  END LOOP;
  IF NOT v_any THEN DBMS_OUTPUT.PUT_LINE('  (none)'); END IF;

  DBMS_OUTPUT.PUT_LINE('==== TRIGGERS ON PER_TRN_* ====');
  FOR r IN (SELECT trigger_name, status, table_name
            FROM   user_triggers
            WHERE  table_name LIKE 'PER_TRN%' OR trigger_name LIKE '%AUDIT%'
            ORDER  BY table_name, trigger_name) LOOP
    DBMS_OUTPUT.PUT_LINE('  ' || RPAD(r.trigger_name,28) || ' ' || RPAD(r.status,9) || ' ' || r.table_name);
  END LOOP;
END;
/


--==============================================================================
-- STEP 1  -  CLEAN AUDIT LOG TABLE (the app already reads erm_trn_audit_log)
--==============================================================================
DECLARE
  n NUMBER;
  PROCEDURE add_col(p_col VARCHAR2, p_def VARCHAR2) IS
    c NUMBER;
  BEGIN
    SELECT COUNT(*) INTO c FROM user_tab_columns
    WHERE table_name = 'ERM_TRN_AUDIT_LOG' AND column_name = p_col;
    IF c = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ERM_TRN_AUDIT_LOG ADD (' || p_col || ' ' || p_def || ')';
      DBMS_OUTPUT.PUT_LINE('STEP 1: added missing column ' || p_col);
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('STEP 1: could not add ' || p_col || ' -> ' || SQLERRM);
  END;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'ERM_TRN_AUDIT_LOG';
  IF n = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE TABLE ERM_TRN_AUDIT_LOG ( ' ||
      '  AUDIT_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, ' ||
      '  AUDIT_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, ' ||
      '  ACTOR_NAME      VARCHAR2(200), ' ||
      '  ACTOR_ROLE      VARCHAR2(60), ' ||
      '  ACTION_TYPE     VARCHAR2(40), ' ||
      '  ENTITY_NAME     VARCHAR2(128), ' ||
      '  ENTITY_ID       VARCHAR2(100), ' ||
      '  DESCRIPTION     VARCHAR2(4000), ' ||
      '  RESULT          VARCHAR2(20) DEFAULT ''SUCCESS'', ' ||
      '  SOURCE_SYSTEM   VARCHAR2(20) DEFAULT ''DB'' ' ||
      ')';
    DBMS_OUTPUT.PUT_LINE('STEP 1: created ERM_TRN_AUDIT_LOG.');
  ELSE
    -- Table exists but may pre-date this schema. Add any columns the audit
    -- writer needs so the procedure can compile against it.
    add_col('AUDIT_TIMESTAMP', 'TIMESTAMP DEFAULT SYSTIMESTAMP');
    add_col('ACTOR_NAME',      'VARCHAR2(200)');
    add_col('ACTOR_ROLE',      'VARCHAR2(60)');
    add_col('ACTION_TYPE',     'VARCHAR2(40)');
    add_col('ENTITY_NAME',     'VARCHAR2(128)');
    add_col('ENTITY_ID',       'VARCHAR2(100)');
    add_col('DESCRIPTION',     'VARCHAR2(4000)');
    add_col('RESULT',          'VARCHAR2(20) DEFAULT ''SUCCESS''');
    add_col('SOURCE_SYSTEM',   'VARCHAR2(20) DEFAULT ''DB''');
    DBMS_OUTPUT.PUT_LINE('STEP 1: ensured audit columns on existing ERM_TRN_AUDIT_LOG.');
  END IF;
END;
/


--==============================================================================
-- STEP 2  -  NON-BLOCKING AUDIT WRITER (the structural fix)
--   Autonomous transaction + WHEN OTHERS => audit can NEVER abort a business DML.
--==============================================================================
CREATE OR REPLACE PROCEDURE ERM_AUDIT_WRITE (
  p_action    IN VARCHAR2,
  p_entity    IN VARCHAR2,
  p_entity_id IN VARCHAR2,
  p_desc      IN VARCHAR2
) AS
  PRAGMA AUTONOMOUS_TRANSACTION;
  v_actor VARCHAR2(200);
BEGIN
  v_actor := NVL(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),
             NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER));
  -- Dynamic INSERT: the procedure compiles regardless of the audit table's
  -- exact shape, so the triggers that depend on it can never become invalid.
  EXECUTE IMMEDIATE
    'INSERT INTO ERM_TRN_AUDIT_LOG ' ||
    '(ACTOR_NAME, ACTION_TYPE, ENTITY_NAME, ENTITY_ID, DESCRIPTION, RESULT, SOURCE_SYSTEM) ' ||
    'VALUES (:1, :2, :3, :4, :5, :6, :7)'
    USING v_actor, p_action, p_entity, p_entity_id, p_desc, 'SUCCESS', 'DB-TRIGGER';
  COMMIT;
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;   -- swallow: audit must never break the business write
END;
/


--==============================================================================
-- STEP 3  -  DROP THE BROKEN TRIGGER, BUILD SAFE ONES
--==============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TRIGGER TRG_RCSA_AUDIT_LOG';
  DBMS_OUTPUT.PUT_LINE('STEP 3: dropped broken trigger TRG_RCSA_AUDIT_LOG.');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('STEP 3: TRG_RCSA_AUDIT_LOG not present (ok).');
END;
/

DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(40);
  v_tabs t_list := t_list(
            'PER_TRN_IDENTIFY_RISK',
            'PER_TRN_RISK_MONITORING',
            'PER_TRN_CONTROL_IMPLEMENTATION');
  v_tab_ok   NUMBER;
  v_has_uuid NUMBER;
  v_name     VARCHAR2(128);
  v_trg      VARCHAR2(32767);
BEGIN
  FOR i IN 1 .. v_tabs.COUNT LOOP
    SELECT COUNT(*) INTO v_tab_ok FROM user_tables WHERE table_name = v_tabs(i);
    IF v_tab_ok = 0 THEN
      DBMS_OUTPUT.PUT_LINE('STEP 3: skip (no table) ' || v_tabs(i));
      CONTINUE;
    END IF;

    SELECT COUNT(*) INTO v_has_uuid
    FROM   user_tab_columns
    WHERE  table_name = v_tabs(i) AND column_name = 'UUID';

    IF v_has_uuid = 0 THEN
      DBMS_OUTPUT.PUT_LINE('STEP 3: skip (no UUID col) ' || v_tabs(i));
      CONTINUE;
    END IF;

    v_name := 'TRG_AUD_' || SUBSTR(v_tabs(i), 9);
    v_trg :=
      'CREATE OR REPLACE TRIGGER ' || v_name || ' ' ||
      'AFTER INSERT OR UPDATE OR DELETE ON ' || v_tabs(i) || ' FOR EACH ROW ' ||
      'DECLARE v_a VARCHAR2(10); v_id VARCHAR2(100); BEGIN ' ||
      '  IF INSERTING THEN v_a := ''CREATE''; v_id := TO_CHAR(:NEW.UUID); ' ||
      '  ELSIF UPDATING THEN v_a := ''UPDATE''; v_id := TO_CHAR(:NEW.UUID); ' ||
      '  ELSE v_a := ''DELETE''; v_id := TO_CHAR(:OLD.UUID); END IF; ' ||
      '  ERM_AUDIT_WRITE(v_a, ''' || v_tabs(i) || ''', v_id, v_a || '' on ' || v_tabs(i) || '''); ' ||
      'EXCEPTION WHEN OTHERS THEN NULL; END;';
    EXECUTE IMMEDIATE v_trg;
    DBMS_OUTPUT.PUT_LINE('STEP 3: created safe trigger ' || v_name);
  END LOOP;
END;
/


--==============================================================================
-- STEP 4  -  RECOMPILE EVERY INVALID OBJECT
--==============================================================================
BEGIN
  DBMS_UTILITY.COMPILE_SCHEMA(schema => USER, compile_all => FALSE);
  DBMS_OUTPUT.PUT_LINE('STEP 4: schema recompiled.');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('STEP 4: COMPILE_SCHEMA note: ' || SQLERRM);
END;
/

DECLARE
  v_sql VARCHAR2(4000);
BEGIN
  FOR r IN (SELECT object_name, object_type FROM user_objects WHERE status = 'INVALID') LOOP
    BEGIN
      IF r.object_type = 'PACKAGE BODY' THEN
        v_sql := 'ALTER PACKAGE "' || r.object_name || '" COMPILE BODY';
      ELSE
        v_sql := 'ALTER ' || r.object_type || ' "' || r.object_name || '" COMPILE';
      END IF;
      EXECUTE IMMEDIATE v_sql;
    EXCEPTION
      WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('STEP 4: still invalid ' || r.object_type || ' ' || r.object_name || ' -> ' || SQLERRM);
    END;
  END LOOP;
END;
/


--==============================================================================
-- STEP 5  -  DATA QUALITY CLEANUP (DQ-01, DQ-02, DQ-05) - column-guarded
--==============================================================================
DECLARE
  v_cnt NUMBER;
  FUNCTION has_col(p_tab VARCHAR2, p_col VARCHAR2) RETURN BOOLEAN IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM user_tab_columns
    WHERE table_name = p_tab AND column_name = p_col;
    RETURN n > 0;
  END;
BEGIN
  -- DQ-01: assessment codes missing the RCSA prefix (e.g. "-2026-002")
  IF has_col('PER_TRN_IDENTIFY_RISK', 'ASSESSMENT_REFERENCE_NUMBER') THEN
    EXECUTE IMMEDIATE
      'UPDATE PER_TRN_IDENTIFY_RISK ' ||
      'SET ASSESSMENT_REFERENCE_NUMBER = ''RCSA-GEN'' || ASSESSMENT_REFERENCE_NUMBER ' ||
      'WHERE ASSESSMENT_REFERENCE_NUMBER IS NOT NULL ' ||
      '  AND REGEXP_LIKE(ASSESSMENT_REFERENCE_NUMBER, ''^-'')';
    v_cnt := SQL%ROWCOUNT;
    EXECUTE IMMEDIATE
      'UPDATE PER_TRN_IDENTIFY_RISK ' ||
      'SET ASSESSMENT_REFERENCE_NUMBER = ''RCSA-'' || TO_CHAR(UUID) ' ||
      'WHERE ASSESSMENT_REFERENCE_NUMBER IS NULL OR TRIM(ASSESSMENT_REFERENCE_NUMBER) IS NULL';
    DBMS_OUTPUT.PUT_LINE('STEP 5: DQ-01 codes fixed = ' || (v_cnt + SQL%ROWCOUNT));
  END IF;

  -- DQ-02: junk / keyboard-mash risk statements (single token, >=8 chars, <20% vowels)
  IF has_col('PER_TRN_IDENTIFY_RISK', 'RISK_STATEMENT') THEN
    EXECUTE IMMEDIATE
      'UPDATE PER_TRN_IDENTIFY_RISK ' ||
      'SET RISK_STATEMENT = ''[Quarantined - invalid entry, please re-enter]'' ' ||
      'WHERE RISK_STATEMENT IS NOT NULL ' ||
      '  AND INSTR(RISK_STATEMENT, '' '') = 0 ' ||
      '  AND LENGTH(RISK_STATEMENT) >= 8 ' ||
      '  AND REGEXP_COUNT(RISK_STATEMENT, ''[aeiou]'', 1, ''i'') <= LENGTH(RISK_STATEMENT) * 0.2';
    DBMS_OUTPUT.PUT_LINE('STEP 5: DQ-02 junk quarantined = ' || SQL%ROWCOUNT);
  END IF;

  -- DQ-05: negative / impossible inherent SLE
  IF has_col('PER_TRN_IDENTIFY_RISK', 'INHERENT_SLE') THEN
    EXECUTE IMMEDIATE
      'UPDATE PER_TRN_IDENTIFY_RISK SET INHERENT_SLE = 0 WHERE INHERENT_SLE < 0';
    DBMS_OUTPUT.PUT_LINE('STEP 5: DQ-05 negative SLE reset = ' || SQL%ROWCOUNT);
  END IF;

  COMMIT;
END;
/


--==============================================================================
-- STEP 6  -  PREVENTIVE GUARD RAILS (ENABLE NOVALIDATE = future rows only)
--==============================================================================
DECLARE
  v_tab NUMBER;
  PROCEDURE add_check(p_tab VARCHAR2, p_cons VARCHAR2, p_chk VARCHAR2) IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM user_constraints
    WHERE table_name = p_tab AND constraint_name = p_cons;
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ' || p_tab ||
                        ' ADD CONSTRAINT ' || p_cons ||
                        ' CHECK (' || p_chk || ') ENABLE NOVALIDATE';
      DBMS_OUTPUT.PUT_LINE('STEP 6: added ' || p_cons);
    ELSE
      DBMS_OUTPUT.PUT_LINE('STEP 6: exists ' || p_cons);
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('STEP 6: skip ' || p_cons || ' -> ' || SQLERRM);
  END;
BEGIN
  SELECT COUNT(*) INTO v_tab FROM user_tables WHERE table_name = 'PER_TRN_IDENTIFY_RISK';
  IF v_tab > 0 THEN
    add_check('PER_TRN_IDENTIFY_RISK', 'CK_IDR_SLE_NONNEG',  'INHERENT_SLE IS NULL OR INHERENT_SLE >= 0');
    add_check('PER_TRN_IDENTIFY_RISK', 'CK_IDR_STAGE_FLAG',  'IS_STAGE_COMPLTED IS NULL OR IS_STAGE_COMPLTED IN (''Y'',''N'')');
    add_check('PER_TRN_IDENTIFY_RISK', 'CK_IDR_APPR_STATUS', 'APPROVAL_STATUS IS NULL OR APPROVAL_STATUS IN (''DRAFT'',''SUBMITTED'',''APPROVED'',''REJECTED'')');
  END IF;
END;
/


--==============================================================================
-- STEP 6B -  RESYNC PRIMARY-KEY SEQUENCES  (fixes ORA-00001 on INSERT)
--   A BEFORE-INSERT trigger assigns UUID from a sequence.  If the sequence has
--   fallen behind MAX(UUID) (common after data imports / manual inserts), every
--   new INSERT collides on the PK.  This advances each table's sequence to
--   MAX(pk)+1 so the next INSERT is guaranteed unique.  Idempotent.
--==============================================================================
DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(40);
  v_tabs t_list := t_list(
            'PER_TRN_IDENTIFY_RISK',
            'PER_TRN_RISK_MONITORING',
            'PER_TRN_CONTROL_IMPLEMENTATION',
            'PER_TRN_INHERENT_RISK_ASSESSMENT',
            'PER_TRN_MITIGATION_PLANS');
  v_tab_ok NUMBER;
  v_pk     VARCHAR2(128);
  v_seq    VARCHAR2(128);
  v_max    NUMBER;
  v_cur    NUMBER;
  v_diff   NUMBER;
BEGIN
  FOR i IN 1 .. v_tabs.COUNT LOOP
    SELECT COUNT(*) INTO v_tab_ok FROM user_tables WHERE table_name = v_tabs(i);
    IF v_tab_ok = 0 THEN
      DBMS_OUTPUT.PUT_LINE('STEP 6B: skip (no table) ' || v_tabs(i));
      CONTINUE;
    END IF;

    -- Identify the PK column (single-column PKs only); default to UUID.
    v_pk := NULL;
    BEGIN
      SELECT cc.column_name INTO v_pk
      FROM   user_constraints c
      JOIN   user_cons_columns cc ON cc.constraint_name = c.constraint_name
      WHERE  c.table_name = v_tabs(i) AND c.constraint_type = 'P'
      AND    (SELECT COUNT(*) FROM user_cons_columns x WHERE x.constraint_name = c.constraint_name) = 1;
    EXCEPTION WHEN OTHERS THEN v_pk := NULL;
    END;
    IF v_pk IS NULL THEN
      SELECT MAX(column_name) INTO v_pk FROM user_tab_columns
      WHERE table_name = v_tabs(i) AND column_name = 'UUID';
    END IF;
    IF v_pk IS NULL THEN
      DBMS_OUTPUT.PUT_LINE('STEP 6B: skip (no single-col PK) ' || v_tabs(i));
      CONTINUE;
    END IF;

    -- Find the sequence the table's triggers depend on (precise).
    v_seq := NULL;
    BEGIN
      SELECT referenced_name INTO v_seq FROM (
        SELECT d.referenced_name
        FROM   user_dependencies d
        WHERE  d.referenced_type = 'SEQUENCE'
        AND    d.name IN (SELECT trigger_name FROM user_triggers WHERE table_name = v_tabs(i))
        ORDER  BY d.referenced_name)
      WHERE ROWNUM = 1;
    EXCEPTION WHEN OTHERS THEN v_seq := NULL;
    END;
    -- Fallback: a sequence whose name contains the table's distinctive token.
    IF v_seq IS NULL THEN
      BEGIN
        SELECT sequence_name INTO v_seq FROM (
          SELECT sequence_name FROM user_sequences
          WHERE  sequence_name LIKE '%' || SUBSTR(v_tabs(i), 9) || '%'
          ORDER  BY sequence_name)
        WHERE ROWNUM = 1;
      EXCEPTION WHEN OTHERS THEN v_seq := NULL;
      END;
    END IF;
    IF v_seq IS NULL THEN
      DBMS_OUTPUT.PUT_LINE('STEP 6B: no sequence found for ' || v_tabs(i) || ' (ok if PK is identity)');
      CONTINUE;
    END IF;

    EXECUTE IMMEDIATE 'SELECT NVL(MAX("' || v_pk || '"),0) FROM ' || v_tabs(i) INTO v_max;
    EXECUTE IMMEDIATE 'SELECT ' || v_seq || '.NEXTVAL FROM DUAL' INTO v_cur;
    v_diff := v_max - v_cur;
    IF v_diff > 0 THEN
      EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || v_seq || ' INCREMENT BY ' || v_diff;
      EXECUTE IMMEDIATE 'SELECT ' || v_seq || '.NEXTVAL FROM DUAL' INTO v_cur;
      EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || v_seq || ' INCREMENT BY 1';
      DBMS_OUTPUT.PUT_LINE('STEP 6B: resynced ' || v_seq || ' for ' || v_tabs(i) ||
                           ' -> now at ' || v_cur || ' (max ' || v_max || ')');
    ELSE
      DBMS_OUTPUT.PUT_LINE('STEP 6B: ' || v_seq || ' already ahead of MAX(' || v_pk ||
                           ')=' || v_max || ' (cur ' || v_cur || ') - ok');
    END IF;
  END LOOP;
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('STEP 6B: note -> ' || SQLERRM);
END;
/


--==============================================================================
-- STEP 7  -  VERIFICATION + SMOKE TEST
--==============================================================================
DECLARE
  v_invalid NUMBER;
  v_tab     NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_invalid FROM user_objects WHERE status = 'INVALID';
  DBMS_OUTPUT.PUT_LINE('==== VERIFY ====');
  DBMS_OUTPUT.PUT_LINE('Invalid objects remaining: ' || v_invalid);

  FOR r IN (SELECT object_name, object_type FROM user_objects WHERE status = 'INVALID'
            ORDER BY object_type, object_name) LOOP
    DBMS_OUTPUT.PUT_LINE('  STILL INVALID: ' || r.object_type || ' ' || r.object_name);
  END LOOP;

  FOR r IN (SELECT trigger_name, status FROM user_triggers
            WHERE table_name LIKE 'PER_TRN%' ORDER BY trigger_name) LOOP
    DBMS_OUTPUT.PUT_LINE('  TRIGGER ' || RPAD(r.trigger_name,28) || ' ' || r.status);
  END LOOP;

  -- Smoke test: prove writes work, then roll back so no test row is kept.
  SELECT COUNT(*) INTO v_tab FROM user_tables WHERE table_name = 'PER_TRN_IDENTIFY_RISK';
  IF v_tab > 0 THEN
    BEGIN
      EXECUTE IMMEDIATE
        'INSERT INTO PER_TRN_IDENTIFY_RISK (RISK_STATEMENT, RISK_TYPE, IS_STAGE_COMPLTED, STATUS) ' ||
        'VALUES (''Remediation smoke test'', ''Operational risk'', ''N'', ''N'')';
      DBMS_OUTPUT.PUT_LINE('SMOKE TEST: INSERT succeeded - writes are working.');
      ROLLBACK;
    EXCEPTION
      WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('SMOKE TEST FAILED: ' || SQLERRM);
    END;
  END IF;
END;
/


--==============================================================================
-- STEP 8  -  PERFORMANCE INDEXES (Eliminates ORDS 10s query timeouts)
--==============================================================================
DECLARE
  PROCEDURE create_idx_if_missing(p_idx VARCHAR2, p_tab VARCHAR2, p_cols VARCHAR2) IS
    c NUMBER;
    t NUMBER;
  BEGIN
    SELECT COUNT(*) INTO t FROM user_tables WHERE table_name = p_tab;
    IF t > 0 THEN
      SELECT COUNT(*) INTO c FROM user_indexes WHERE index_name = p_idx;
      IF c = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ' || p_idx || ' ON ' || p_tab || ' (' || p_cols || ')';
        DBMS_OUTPUT.PUT_LINE('STEP 8: created index ' || p_idx || ' on ' || p_tab);
      ELSE
        DBMS_OUTPUT.PUT_LINE('STEP 8: index ' || p_idx || ' already exists');
      END IF;
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('STEP 8: note on ' || p_idx || ' -> ' || SQLERRM);
  END;
BEGIN
  create_idx_if_missing('IDX_PER_IDR_UUID_STAGE', 'PER_TRN_IDENTIFY_RISK', 'UUID, IS_STAGE_COMPLTED');
  create_idx_if_missing('IDX_PER_IDR_PROC_UUID',  'PER_TRN_IDENTIFY_RISK', 'BUSINESS_PROCESS_UUID');
  create_idx_if_missing('IDX_PER_CTL_RISK_UUID',  'PER_TRN_CONTROL_IMPLEMENTATION', 'IDENTIFY_RISK_UUID');
  create_idx_if_missing('IDX_PER_MON_RISK_UUID',  'PER_TRN_RISK_MONITORING', 'IDENTIFY_RISK_UUID');
  create_idx_if_missing('IDX_ERM_AUD_TIME',       'ERM_TRN_AUDIT_LOG', 'AUDIT_TIMESTAMP DESC');
END;
/

